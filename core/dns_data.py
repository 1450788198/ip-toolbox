def isp_providers(province: str) -> list:
    """某省运营商 DNS：[(运营商, 主, 备, 说明)]，缺数据的运营商不显示"""
    rows = []
    for isp, src in (("中国电信", DNS_TELECOM), ("中国联通", DNS_UNICOM),
                     ("中国移动", DNS_MOBILE)):
        if province in src:
            primary, secondary = src[province]
            rows.append((isp, primary, secondary, f"{province}省内节点"))
    return rows


def ping_ms(ip: str):
    """单次 ping 延迟（毫秒）；空地址或不通返回 None"""
    if not ip:
        return None
    try:
        p = subprocess.run(["ping", "-c", "1", "-W", "2000", ip],
                           capture_output=True, text=True, timeout=5)
    except Exception:
        return None
    if p.returncode != 0:
        return None
    m = re.search(r"time[=<]([\d.]+)\s*ms", p.stdout)
    return float(m.group(1)) if m else 0.0


def ms_level(ms) -> str:
    """延迟分级：ok / warn / bad"""
    if ms is None:
        return "bad"
    if ms < 30:
        return "ok"
    if ms < 100:
        return "warn"
    return "bad"
